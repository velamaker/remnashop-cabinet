/**
 * Доля сервера в трафике за 30 дней.
 *
 * ПОЧЕМУ ДОЛИ, А НЕ ГИГАБАЙТЫ. Раскладка по серверам приходит из статистики нод
 * панели, а большое число «израсходовано» на той же странице — из счётчика
 * пользователя. Это РАЗНЫЕ источники: на бою счётчик стабильно в 1.5–2 раза больше
 * суммы по нодам (сверено по всем активным подпискам, расхождение есть и у панели
 * самой по себе). Два числа рядом, которые не сходятся, человек читает как обман —
 * а доля отвечает на вопрос, ради которого карточку и открывают: каким сервером я
 * пользуюсь чаще.
 */
export function serverShare(total: number, sum: number): number {
  if (!Number.isFinite(total) || !Number.isFinite(sum) || sum <= 0 || total <= 0) return 0;
  return Math.round((total / sum) * 100);
}

/**
 * Подпись доли. Ноль бывает двух видов, и путать их нельзя: «трафика не было»
 * и «был, но меньше процента» — во втором случае «0%» читается как поломка.
 */
export function serverShareLabel(total: number, sum: number): string {
  const share = serverShare(total, sum);
  if (share > 0) return `${share}%`;
  return total > 0 && sum > 0 ? "<1%" : "0%";
}
