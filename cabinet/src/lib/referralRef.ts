/**
 * Реф-код, пришедший в ссылке приглашения, и его досчёт после входа.
 *
 * ЗАЧЕМ ЭТО НУЖНО. Ссылка приглашения ведёт на `/register?ref=КОД`, и почтовая
 * регистрация отправляет код прямо в форме. У входа через Telegram такого поля
 * нет вовсе — ни в форме, ни на сервере, — поэтому приглашение, завершённое
 * телеграмом, не засчитывалось никак и молча. Учитывая, что телеграмом входят
 * 1069 человек из 1090, реферальная программа кабинета не работала ни разу.
 *
 * ЧТО ДЕЛАЕМ. Код из адреса запоминаем при любом заходе на любую страницу и
 * отдаём серверу ПОСЛЕ того, как человек вошёл, — каким угодно способом. Так
 * работают все ветки сразу: виджет Telegram, вход из мини-приложения, OIDC с
 * переходом на oauth.telegram.org и обратно, и обычная почтовая регистрация
 * (там сервер просто ответит «уже привязан» и ничего не сделает).
 *
 * ПОЧЕМУ localStorage, А НЕ ПАМЯТЬ ВКЛАДКИ. Вход через OIDC уводит браузер на
 * чужой домен и возвращает обратно; часть клиентов Telegram при этом открывает
 * НОВУЮ вкладку, и sessionStorage той вкладке уже не достанется. localStorage
 * переживает и это. Ключ снимаем сразу после попытки — второй раз он не нужен,
 * а сервер и так откажет повторной привязке.
 *
 * Доступ к хранилищу обёрнут в try/catch: в приватном окне и при выключенных
 * данных сайта обращение к нему БРОСАЕТ, и без этого падала бы вся страница.
 */

const KEY = "pending_referral_code";

// Тот же формат, что генерирует бот: короткий буквенно-цифровой код. Проверяем
// не ради безопасности (решает сервер), а чтобы не хранить мусор из адреса.
const CODE_RE = /^[A-Za-z0-9_-]{1,64}$/;

export function captureReferralCode(search: string = window.location.search): void {
  try {
    const code = new URLSearchParams(search).get("ref");
    if (code && CODE_RE.test(code)) {
      localStorage.setItem(KEY, code);
    }
  } catch {
    // Хранилище недоступно — приглашение просто не досчитается, ломать вход незачем.
  }
}

export function readReferralCode(): string | null {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
}

export function clearReferralCode(): void {
  try {
    localStorage.removeItem(KEY);
  } catch {
    /* см. выше */
  }
}
