# shellcheck shell=bash
# Благодарность и адреса для поддержки проекта — в конце установки и обновления.
#
# ЗАЧЕМ. Проект живёт на пожертвования, а человек, который только что поставил или
# обновил кабинет, — ровно тот, кому есть за что сказать спасибо. Показываем в самом
# конце, когда всё уже сделано, и только живому человеку в терминале: из cron и
# других запусков без терминала читать это некому.
#
# ОТКУДА АДРЕСА. Из README.md, раздел «Поддержать проект», — это та же страница, что
# видят на GitHub. Владелец меняет адреса в одном месте, а README лежит в каждой
# установке: и в git-клоне, и в архиве с GitHub. Раздел не нашёлся (переименовали,
# README нет) — вместо адресов ссылка на репозиторий, а не пустота и не ошибка.
#
# КАК ПОДКЛЮЧАТЬ. Через `.`; при подключении ничего не печатает. Хозяева работают под
# `set -euo pipefail`, а установка к этому моменту уже прошла — ронять её из-за
# благодарности нельзя, поэтому каждая функция здесь страхуется сама и возвращает 0.
#
# Без терминала баннер молчит. RS_THANKS_FORCE=1 показывает его и без терминала —
# это для стенда scripts/tests/update-sh.sh, а не для людей.

THANKS_REPO_URL="https://github.com/velamaker/remnashop-cabinet"

# Раздел README с донатами: от заголовка «## … Поддержать проект …» до следующего «## ».
_thanks_section() {
  [ -r "$1" ] || return 0
  sed -n '/^## .*Поддержать проект/,/^## /p' "$1" 2>/dev/null || true
}

# Строки «сеть|адрес» из таблицы раздела. Пропускаем только то, что похоже на сеть и
# на адрес кошелька: README мог прийти из форка или правки на GitHub, а терминал
# исполняет управляющие последовательности — сырой текст из файла сюда не пускаем.
thanks_rows() {
  _thanks_section "${1:-README.md}" \
    | sed -nE 's/^\|[[:space:]]*\*\*([A-Za-z0-9 ()-]{1,40})\*\*[[:space:]]*\|[[:space:]]*`([A-Za-z0-9_-]{16,128})`[[:space:]]*\|.*$/\1|\2/p' \
    || true
}

# Монета из заголовка: «## ❤️ Поддержать проект (USDT)» → «USDT». Нет скобок — пусто.
thanks_coin() {
  _thanks_section "${1:-README.md}" \
    | sed -nE '1s/^## .*Поддержать проект[^(]*\(([A-Za-z0-9 ,]{1,20})\).*$/\1/p' \
    || true
}

thanks_banner() {
  if [ ! -t 1 ] && [ "${RS_THANKS_FORCE:-}" != 1 ]; then return 0; fi
  local readme="${1:-README.md}" rows coin net addr b="" d="" r="" line
  if [ -t 1 ]; then b=$'\e[1m'; d=$'\e[2m'; r=$'\e[0m'; fi
  line="────────────────────────────────────────────────────────────"
  rows="$(thanks_rows "$readme")"
  coin="$(thanks_coin "$readme")"

  printf '\n  %s%s%s\n' "$d" "$line" "$r"
  printf '  %sСпасибо, что выбрали velamaker!%s ❤\n' "$b" "$r"
  if [ -n "$rows" ]; then
    printf '  Если хотите, чтобы проект развивался дальше, — поддержите его%s:\n\n' "${coin:+ (${coin})}"
    while IFS='|' read -r net addr; do
      [ -n "$addr" ] || continue
      printf '    %-18s %s%s%s\n' "$net" "$b" "$addr" "$r"
    done <<EOF
$rows
EOF
    printf '\n  %sОтправляйте строго в указанной сети, иначе средства можно потерять.%s\n' "$d" "$r"
    printf '  %sВсе адреса и новости проекта: %s%s\n' "$d" "$THANKS_REPO_URL" "$r"
  else
    printf '  Если хотите, чтобы проект развивался дальше, — поддержать его можно здесь:\n'
    printf '  %s%s%s\n' "$b" "$THANKS_REPO_URL" "$r"
  fi
  printf '  %s%s%s\n' "$d" "$line" "$r"
  return 0
}
