"""[OVERLAY] Rich-вид админ-уведомлений (Bot API 10.1, метод sendRichMessage).

Вместо простыни текста — заголовок, разделы и таблица «показатель → значение».
Почерк — НАШЕГО кабинета, а не чужого бота: надзаголовок-хештег над крупным
заголовком, надписи разделов заглавными без иконок, таблица без рамок и зебры
(в кабинете строка данных отбита волосяной линией, а не сеткой), тихая подпись
и под ней крупное число вместо строки таблицы, настоящие списки вместо нарисованных
«• » и «1. ». Соответствия взяты с конкретных экранов кабинета: карточка одной
транзакции (надписи разделов, короткие подписи полей), StatCard на «Статистике»
(крупное число), строка узла на «Статусе сервиса» (точка состояния + имя).

Наши уведомления уже собраны из фрагментов вида «• <b>Ключ</b>: значение»
внутри <blockquote> (см. utils.ftl, frg-*), поэтому ничего переписывать в
шаблонах не нужно: здесь разбираем готовый HTML и перекладываем буллеты в
<table>. Уведомление может описывать несколько объектов сразу («💰 Платеж»,
«👤 Пользователь», «🤝 Пригласитель»), у каждого свой заголовок в шаблоне —
таблицу делаем на каждый такой раздел отдельно. Если разобрать нечего (нет ни
одной пары ключ-значение) — возвращаем None, и уведомление уходит обычным
send_message.

ВАЖНО: весь почерк живёт ТОЛЬКО здесь, в сборщике, и ни одного тега мы не
добавляем в .ftl. Классический путь (send_message с parse_mode=HTML) понимает
лишь узкий набор тегов — b/i/u/s/code/pre/blockquote/a/tg-spoiler/tg-emoji.
Просочись <h3>, <mark>, <ul> или <table> в шаблон — Telegram ответит «can't
parse entities», а notification.py такой TelegramBadRequest пробрасывает
наружу: уведомление не деградирует, а ТЕРЯЕТСЯ целиком. Пока правки в
сборщике, откат (NOTIFY_RICH=false или тумблер в админке) возвращает в
точности прежний классический вид.

В aiogram 3.25 метода sendRichMessage нет (появился в 3.29), а поднимать
aiogram нельзя — на нём завязан aiogram_dialog со всеми диалогами бота.
Поэтому зовём Bot API напрямую. Если сервер метод не знает — запоминаем это
до перезапуска и больше не пробуем, всё продолжает работать по-старому.

Тумблер: NOTIFY_RICH (по умолчанию включён).
"""

import html as html_lib
import os
import re
from datetime import datetime, timezone
from typing import Any, Optional

from aiogram import Bot
from loguru import logger

# Сервер не поддерживает rich — латч до перезапуска процесса.
_rich_unavailable = False

# «• <b>Название</b>: 🇩🇪 Germany» → ключ + значение (значение остаётся сырым HTML).
_ROW_RE = re.compile(r"^\s*•\s*<b>(?P<key>.+?)</b>\s*:\s*(?P<value>.*?)\s*$")
# Заголовок уведомления — первая строка целиком в <b>…</b>.
_TITLE_RE = re.compile(r"^\s*<b>(?P<title>.+?)</b>\s*$")
# Подзаголовок раздела — ровно то, что в шаблонах пишется через hdr-* :
# строка ЦЕЛИКОМ в <b>…</b> и с двоеточием на конце («<b>👤 Пользователь</b>:»).
# Ловить любую строку с двоеточием на конце нельзя: под это правило попадали
# обычные предложения («Traceback (most recent call last):», «Причины:») —
# раздел из них выходил пустым и выбрасывался вместе с текстом.
_SUBHEAD_RE = re.compile(r"^\s*<b>(?P<head>.+?)</b>\s*:\s*$")
_TAG_RE = re.compile(r"<[^>]+>")

# ───────────────────────── почерк кабинета ──────────────────────────────
# Всё, что ниже, переводит наш текст из чужого «бот-стиля» в стиль кабинета.
# Ни одно правило не знает про конкретное событие: работаем по форме строки,
# чтобы новое уведомление подхватывалось само и ничего не приходилось
# дублировать в шаблонах.

# Значок — это ЭМОДЗИ, и только оно. Критерий «непробельный кусок без букв и
# цифр» отрезал у подписи ведущее тире, кавычку, скобку и стрелку — то есть
# портил текст, написанный руками («— Примечание» становилось «Примечание»).
# Диапазоны покрывают ровно то, чем подписаны наши шаблоны: 💰 👤 🖥 🆕 ⏳ 📈 🎁
# ⚠️ 🛑 🟢 ✅ ☀️. Незнакомый значок теперь просто остаётся в тексте — это
# заметно, но честно, в отличие от съеденного знака препинания.
_EMOJI = (
    "\U0001F000-\U0001FAFF"  # пиктограммы и эмодзи: 💰 🖥 🆕 🛑 🟢 🎁
    "\u2600-\u27BF"          # символы и дингбаты: ☀ ⚠ ✅ ❗ ➡
    "\u231A-\u23FA"          # часы и управление: ⌚ ⌛ ⏳ ⏰
    "\u25A0-\u25FF"          # геометрия: ▪ ◼ ◾
    "\u2B00-\u2BFF"          # ⬆ ⭐ ⭕
    "\u2049\u203C\u3030\u303D\u3297\u3299"   # ⁉ ‼ 〰 〽 ㊗ ㊙
    "\uFE0F\u200D\u20E3"    # селектор варианта, ZWJ и keycap — части значка
)
# Пробел после значка обязателен: он отделяет значок от подписи и заодно
# защищает значения вроде «≤ 3 дней».
_LEAD_ICON_RE = re.compile(rf"^[{_EMOJI}]+\s+", re.UNICODE)

# Заголовок события в шаблонах — «🔅 Событие: Покупка подписки!». Кабинет
# называет экраны существительными без восклицаний («Статистика», «Детали
# транзакции»), поэтому канцелярское «Событие:» и «!» срезаем. Обязательное
# «Событие:» делает правило no-op для «☀️ Сводка за 07.08», «🖥 Мониторинг нод»
# и «⚠️ Внимание! Ваша подписка закончится через 3 дня».
_EVENT_TITLE_RE = re.compile(r"^\s*(?P<icon>\S+\s+)?Событие:\s*(?P<title>.+?)!?\s*$")
# 🔅 в заголовке не значит ничего — это украшение, его убираем. Значок,
# который несёт смысл (⚠️ у проблемных событий), оставляем: в кабинете иконки
# как раз смысловые — <CreditCard/>, <Activity/>.
_MEANINGLESS_TITLE_ICONS = ("🔅",)

# Строка целиком из одного хештега — это надзаголовок (в кабинете mono-label
# стоит НАД заголовком, StatusPage/LandingPage), а не часть текста. В <code>
# его заворачивать нельзя: Telegram сам делает хештег кликабельным.
_HASHTAG_RE = re.compile(r"^#\S+$")

# Короткие подписи полей — ровно те слова, которыми эти же данные подписаны в
# кабинете (карточка транзакции: «Срок, дней», «Устройств», «Трафик», надпись
# раздела «Оплата»; «Статистика»: «Истекают скоро»). Бот сегодня говорит теми
# же данными другим голосом — «Лимит устройств», «Длительность». Побочная
# выгода: строка таблицы становится на 5-8 знаков уже, и пары реже уезжают
# из таблицы вниз.
_KEY_RENAMES = {
    "Лимит трафика": "Трафик",
    "Лимит устройств": "Устройств",
    "Длительность": "Срок",
    "Способ оплаты": "Оплата",
}
# «Истекают через 3 дня» — срок задаётся настройкой, поэтому по шаблону.
_KEY_RENAME_PATTERNS = ((re.compile(r"^Истекают через .+$"), "Истекают скоро"),)
# «Устройств: 3 устройства» — после переименования подпись и значение говорят
# одно и то же дважды. В кабинете в этой строке стоит голое число.
_DEVICE_COUNT_RE = re.compile(r"^(?P<count>\d+)\s+устройств\w*$")

# Главное число уведомления. В кабинете это StatCard: тихая подпись, под ней
# крупное значение (AdminDashboardPage.tsx — <p text-xs text-fg-muted>{label}</p>
# и следом <p text-2xl font-bold>{value}</p>), а не строка таблицы наравне со
# счётчиками. Сегодня выручка вылетает из таблицы не по замыслу, а потому что
# значение длиннее ячейки, — и оказывается НИЖЕ менее важных счётчиков.
_HERO_KEYS = ("сумма", "выручка")
# ...но только если это действительно ЧИСЛО. В день без продаж выручка приходит
# словами («нет оплат»), и крупным шрифтом такое читается как крик.
_HAS_DIGIT_RE = re.compile(r"\d")

# Нарисованные руками список и нумерация: их должен рисовать сам клиент.
# Номер запоминаем: по нему видно, идут ли пункты подряд (см. _details_block).
_BULLET_RE = re.compile(r"^[•·]\s+(?P<text>.+)$")
_NUMBERED_RE = re.compile(r"^(?P<num>\d+)\.\s+(?P<text>.+)$")
# Строка-хвост списка («…и ещё 7 — весь список в админке»): в <ol> ей нельзя,
# иначе клиент выдаст ей следующий номер и список соврёт.
_LIST_TAIL_RE = re.compile(r"^[.…]")

# Шапка объекта в алертах: «🛑 <b>Germany-1</b> — xray не работает уже 22 мин…».
# Это строка узла со «Статуса сервиса» (точка состояния + имя), а не рядовой
# факт, — поднимаем её в надпись раздела.
#
# Одной формы строки для этого МАЛО: под неё подходит и фраза, написанная
# руками, — рассылка (web/endpoints/admin/broadcasts.py) и «написать
# пользователю» (web/endpoints/admin/subscriptions.py) шлют текст владельца как
# есть, через raw-message. «💥 <b>Акция</b> — минус 30%» превращалась в
# заголовок ЗАГЛАВНЫМИ: владелец написал одно, а получатель прочитал другое.
# Поэтому решение принимается по СОСЕДЯМ строки (см. _free_lines), а значок
# должен быть настоящим эмодзи, а не любым знаком препинания.
_OBJECT_HEAD_RE = re.compile(
    rf"^(?P<icon>[{_EMOJI}]+)\s+<b>(?P<name>[^<]{{1,64}})</b>\s*(?:[—–-]|:)\s*(?P<rest>.+)$"
)
# Заглавные — только для имени из букв, цифр, пробела и дефиса. URL и хост
# заглавными не пишут, а в экранированном тексте .upper() ещё и сломал бы
# сущность («&amp;» → «&AMP;»).
_UPPERCASABLE_RE = re.compile(r"^\w[\w\s-]*$", re.UNICODE)
# 🛑 выпадает из принятой у нас палитры 🟢/🟡/🔴 (utils.ftl, access-mode —
# там же, где её видит владелец в кабинете на «Статусе сервиса»).
_ICON_PALETTE = {"🛑": "🔴"}

# Значение, которое кабинет метит моноширинным независимо от длины: UUID, IP,
# host:port, hwid/хеш, числовой id (в кабинете «#123» — font-mono). Раньше
# критерием была длина, из-за чего короткий идентификатор оставался обычным
# текстом, а длинная фраза с дефисами — нет.
_IDENT_RE = re.compile(
    r"^(?:"
    r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"  # UUID
    r"|\d{1,3}(?:\.\d{1,3}){3}(?::\d+)?"                       # IPv4 и IPv4:порт
    r"|[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?(?:\.[A-Za-z0-9-]+)+(?::\d+)?"  # host[:порт]
    r"|[0-9a-fA-F]{16,}"                                       # хеш / hwid
    r"|[A-Za-z0-9_-]{20,}"                                     # токен без точек и слэшей
    r"|\d{5,}"                                                 # числовой id
    r")$"
)
# Ссылка сюда намеренно не попадает: голый URL Telegram делает кликабельным сам,
# а <code> вокруг него ссылку убивает. Раньше длинный URL заворачивался в <code>
# просто за длину — и переставал открываться по нажатию.


def rich_enabled() -> bool:
    if _rich_unavailable:
        return False
    return (os.environ.get("NOTIFY_RICH") or "true").strip().lower() in (
        "1", "true", "yes", "on", "да",
    )


def _mark_unavailable(reason: str) -> None:
    global _rich_unavailable
    if not _rich_unavailable:
        logger.warning(f"[OVERLAY] Bot API не поддерживает sendRichMessage ({reason}) — обычный вид")
    _rich_unavailable = True


def logo_src() -> str:
    """Абсолютный URL логотипа для шапки rich-сообщения (или '' — нет логотипа).

    Тот же логотип, что в кабинете и в письмах: assets/branding.json →
    /api/appearance/logo, абсолютный по WEB_CABINET_URL (Telegram грузит картинку
    снаружи, относительный путь ему не годится).
    """
    try:
        from src.web.endpoints.public.appearance import (  # noqa: PLC0415
            load_branding,
            logo_url,
        )

        rel = logo_url(load_branding().get("logo_file"))
        if not rel:
            return ""
        base = (os.environ.get("WEB_CABINET_URL") or "").strip().rstrip("/")
        if not base:
            origins = (os.environ.get("APP_ORIGINS") or "").strip()
            base = origins.split(",")[0].strip().rstrip("/") if origins else ""
        return f"{base}{rel}" if base.startswith("http") else ""
    except Exception:  # noqa: BLE001
        return ""


# Сколько знаков «ключ + значение» реально видно в строке таблицы на телефоне.
# Цифры не с потолка, а померены по скриншоту владельца (7 августа, событие
# «Первое подключение»): колонка ключей показывала «Лимит устройств» — 15 знаков,
# а из 36-значного UUID в колонке значений было видно 23, дальше кончался экран.
# Значит на строку приходится примерно 38 знаков; берём 36 с запасом на рамку.
#
# Горизонтальной прокрутки у таблиц нет — что не влезло, то не прочитать. Хуже
# того, значения были выровнены по правому краю: одно длинное значение растянуло
# колонку за границу экрана и УТАЩИЛО ТУДА ЖЕ все короткие значения целиком —
# «Почта», «Статус», «Трафик», «Лимит устройств» выглядели пустыми, хотя данные
# в них были. Поэтому теперь: (1) значения по левому краю — если что-то и не
# влезет, видно хотя бы начало; (2) широкие пары уезжают из таблицы под неё.
_ROW_FITS = 36
# Сколько знаков заголовка ещё читаются как заголовок. Строка телефона — те же
# ~38 знаков; две строки крупным кеглем глаз берёт за заголовок, а дальше это уже
# абзац, набранный заголовочным размером, — та самая стена текста.
_TITLE_FITS = 76
# Сколько знаков помещается в саму колонку значений (те же 38 минус типичный
# ключ). Значение длиннее в ячейке уже не прочитать: ячейки не переносятся.
_VALUE_FITS = 22

# Сворачиваемая цитата «<blockquote expandable>…</blockquote>» — это ГОТОВЫЙ
# блок, а не пары «ключ: значение»: его нельзя разбирать построчно. Раньше такой
# блок молча пропадал (цикл ниже срезает теги цитаты и ищет буллеты), поэтому
# вынимаем его из текста ДО разбора и доставляем как есть — после таблицы.
_EXPANDABLE_RE = re.compile(
    r"<blockquote\s+expandable[^>]*>(?P<body>.*?)</blockquote>", re.S | re.I
)

# Значение «ни о чём»: пусто или один разделитель, оставшийся от пустых кусков
# (шаблон «{ $traffic_used } / { $traffic_limit }» без данных даёт голый «/»).
# Ноль и прочерк сюда НЕ входят: «0 МБ» и «—» — это факты, их терять нельзя.
_BLANK_VALUE_RE = re.compile(r"^[\s/|,;·]*$")

# Пара «ключ → значение», значение остаётся сырым HTML (ссылка, <code>, …).
_Pair = tuple[str, str]
# Раздел уведомления: заголовок («💰 Платеж»), его пары и его свободные строки
# (текст сборки, текст ошибки — там пар нет вообще). Заголовка может не быть
# (сводка, короткий алерт) — тогда None. Свободные строки живут В РАЗДЕЛЕ, а не
# в общей куче: иначе текст всплывал в начало уведомления, а осиротевший
# заголовок подписывал чужую таблицу.
_Section = tuple[Optional[str], list[_Pair], list[str]]
# Пара с посчитанными длинами: (порядок, ключ, значение, длина ключа, длина значения).
_Measured = tuple[int, str, str, int, int]


def _plain(fragment: str) -> str:
    """Видимый текст без разметки — по нему считаем ширину и пустоту.

    Длину нельзя мерить по HTML: в `<a href="tg://user?id=…">@user</a>` глазами
    видно девять знаков, а в строке их под полсотни.
    """
    return html_lib.unescape(_TAG_RE.sub("", fragment)).strip()


def _is_blank(value: str) -> bool:
    """True — данных в значении нет, печатать пару не нужно.

    Пустая ячейка ничего не сообщает, но занимает строку и расширяет колонку
    ключей. Так выходит у пользователей, заведённых прямо в панели: у бота нет
    ни почты, ни статистики, и в таблице остаются подписи без значений.
    """
    return bool(_BLANK_VALUE_RE.match(_plain(value)))


def _tidy_spaces(fragment: str) -> str:
    """Схлопывает подряд идущие пробелы В ТЕКСТЕ, не трогая теги.

    Шаблоны склеивают значения из кусков («{ $amount }{ $currency } { скидка }»),
    и при пустой скидке остаётся «299₽   ». В ячейке таблицы переноса нет —
    каждый лишний пробел съедает знак ширины, а в крупном числе ещё и заметен
    глазом. Резать по всей строке нельзя: пробелы бывают внутри href.
    """
    return "".join(
        part if part.startswith("<") else re.sub(r"\s{2,}", " ", part)
        for part in re.split(r"(<[^>]+>)", fragment)
    )


def _drop_icon(text: str) -> str:
    """Убирает ведущий значок из подписи («💰 Платеж» → «Платеж»).

    В кабинете иконку рисует компонент рядом с текстом, а сама подпись — голая
    («Всего», «Активных», «Устройств»). Значок в каждой строке данных — почерк
    чужого бота; попутно он отнимал по два знака ширины у каждой строки.
    """
    return _LEAD_ICON_RE.sub("", text).strip()


def _section_label(heading: str) -> str:
    """Надпись раздела: без значка, заглавными.

    В карточке транзакции разделы подписаны `text-xs uppercase tracking-wide
    text-fg-subtle` — «ОПЛАТА», «ТАРИФ», «ПОЛЬЗОВАТЕЛЬ». Регистр несёт ту роль,
    которую в вебе несут размер и разрядка; разрядку пробелами имитировать
    нельзя — ломается поиск по сообщению и копирование.

    Заглавные применяем ТОЛЬКО к уже очищенному тексту заголовка и никогда к
    значениям: «ЮKassa» превратилась бы в «ЮKASSA», а идентификатор с учётом
    регистра просто перестал бы работать.
    """
    return _drop_icon(heading).upper()


def _repaint(icon: str) -> str:
    """Приводит значок состояния к нашей палитре 🟢/🟡/🔴."""
    return _ICON_PALETTE.get(icon, icon)


def _clean_title(title: str) -> str:
    """Заголовок уведомления по-кабинетному: существительное без канцелярита.

    «🔅 Событие: Покупка подписки!» → «Покупка подписки».
    «⚠️ Событие: Платеж возвращен!» → «⚠️ Платеж возвращен» — значок остаётся,
    он единственный признак «это про проблему».
    «🛑 Бэкап БД» → «🔴 Бэкап БД» — палитра одна на всё.
    """
    match = _EVENT_TITLE_RE.match(title)
    if not match:
        # Не событие («Сводка за 07.08», «Мониторинг нод», «🛑 Бэкап БД») —
        # текст не трогаем, только приводим значок к общей палитре.
        head, _, tail = title.partition(" ")
        return f"{_repaint(head)} {tail}" if tail and head in _ICON_PALETTE else title
    icon = (match.group("icon") or "").strip()
    if icon in _MEANINGLESS_TITLE_ICONS:
        icon = ""
    return f"{_repaint(icon)} {match.group('title')}".strip()


def _key_label(key: str) -> str:
    """Подпись строки данных словами кабинета."""
    label = _drop_icon(_plain(key))
    renamed = _KEY_RENAMES.get(label)
    if renamed:
        return renamed
    for pattern, replacement in _KEY_RENAME_PATTERNS:
        if pattern.match(label):
            return replacement
    return label


def _key_value(key: str, value: str) -> str:
    """Значение с учётом того, что подпись уже могла его назвать.

    После переименования «Лимит устройств» → «Устройств» строка читалась бы
    «Устройств · 3 устройства». В кабинете здесь стоит голое число.
    """
    # «<» в значении — своя разметка (<code>, ссылка): её терять нельзя, поэтому
    # сокращаем только голый текст.
    if "<" not in value and _KEY_RENAMES.get(_drop_icon(_plain(key))) == "Устройств":
        match = _DEVICE_COUNT_RE.match(_plain(value))
        if match:
            return match.group("count")
    return value


def _table_width(items: list[_Measured]) -> int:
    """Сколько знаков таблица занимает на экране.

    Колонки задают НЕЗАВИСИМО самый длинный ключ и самое длинное значение —
    обычно из разных строк. Поэтому складываем два максимума, а не длину
    какой-то одной пары.
    """
    if not items:
        return 0
    return max(item[3] for item in items) + max(item[4] for item in items)


def _top_two(lengths: list[int]) -> tuple[int, int]:
    """Самая большая длина и та, что останется, если её единственного носителя убрать.

    Второе число — это максимум без одного экземпляра первого. Если максимум
    держат несколько строк, оно равно первому: убрать одну строку ширину не
    изменит.
    """
    first = second = 0
    for length in lengths:
        if length > first:
            first, second = length, first
        elif length > second:
            second = length
    return first, second


def _split_rows(rows: list[_Pair]) -> tuple[list[_Pair], list[_Pair]]:
    """Делит пары на строки таблицы и «широкие» пары, которые пойдут под ней.

    Ширину колонки задаёт самое длинное значение, поэтому один UUID (36 знаков)
    растягивает всю таблицу за экран. Такую пару печатаем отдельной строкой:
    там значению доступна вся ширина сообщения, оно переносится и видно целиком.
    """
    items: list[_Measured] = [
        (order, key, value, len(_plain(key)), len(_plain(value)))
        for order, (key, value) in enumerate(rows)
    ]
    table = [item for item in items if item[4] <= _VALUE_FITS]
    aside = [item for item in items if item[4] > _VALUE_FITS]

    # Даже если каждое значение по отдельности приемлемо, вместе с длинными
    # ключами таблица может не влезть — выносим лишние пары, пока не влезет.
    while table and _table_width(table) > _ROW_FITS:
        widest_key, next_key = _top_two([item[3] for item in table])
        widest_value, next_value = _top_two([item[4] for item in table])

        def width_without(item: _Measured) -> int:
            """Ширина таблицы, если убрать эту строку.

            Строка сужает колонку, только когда держит её максимум одна: если
            такой же длины есть ещё одна, колонка останется прежней.
            """
            key = next_key if item[3] == widest_key else widest_key
            value = next_value if item[4] == widest_value else widest_value
            return key + value

        # Выносить имеет смысл только держателя одного из двух максимумов: без
        # остальных таблица не сузится ни на знак. Раньше жертву искали по сумме
        # len(ключ) + len(значение) — под нож попадали пары, которые прекрасно
        # влезали («Режим», «Сумма балансов» у владельца), а настоящий длинный
        # ключ оставался в таблице, и вынос повторялся снова и снова.
        holders = [
            item
            for item in table
            if item[3] == widest_key or item[4] == widest_value
        ]
        # Длинный ключ и длинное значение сидят в разных строках, и какая из них
        # мешает больше — видно только по итоговой ширине. При равенстве
        # выносим ту, что шире сама по себе.
        worst = min(holders, key=lambda item: (width_without(item), -(item[3] + item[4])))
        table.remove(worst)
        aside.append(worst)

    aside.sort(key=lambda item: item[0])  # порядок как в шаблоне, а не как выносили
    return (
        [(key, value) for _, key, value, _, _ in table],
        [(key, value) for _, key, value, _, _ in aside],
    )


def _aside_value(value: str) -> str:
    """Значение для строки под таблицей.

    Своя разметка (`<code>`, ссылка) в значении уже есть — оставляем как есть.
    Идентификатор (UUID, IP, host:port, hwid, числовой id) заворачиваем в
    `<code>`: кабинет метит такое моноширинным независимо от длины («#123» —
    font-mono в списке пользователей), а в Telegram моноширинный текст ещё и
    выделяется по нажатию — такое обычно копируют.

    Критерий — ВИД значения, а не длина: по длине короткий идентификатор
    оставался обычным текстом, а длинная фраза с дефисами моноширинной не
    становилась. Обычный текст не трогаем — «25 %» моноширинным выглядит нелепо.
    """
    if "<" not in value and _IDENT_RE.match(_plain(value)):
        return f"<code>{value.strip()}</code>"
    return value


def _take_expandable(text: str) -> tuple[str, list[str]]:
    """Вынимает сворачиваемые цитаты — их содержимое разбирать нельзя.

    Возвращает текст без них и тела цитат «как есть». Разбор ниже понимает
    только буллеты, а внутри такой цитаты — готовый список (кто истекает и т.п.):
    попади он в общий цикл, строки либо расползлись бы по таблице, либо исчезли
    вместе с тегом цитаты.
    """
    blocks: list[str] = []

    def _grab(match: re.Match[str]) -> str:
        blocks.append(match.group("body"))
        return "\n"  # на месте блока оставляем разрыв, чтобы соседние строки не слиплись

    return _EXPANDABLE_RE.sub(_grab, text), blocks


def _free_lines(lines: list[str]) -> list[str]:
    """Свободные строки уведомления (алерты, текст ошибки) — блоками кабинета.

    Три правила, все по форме строки:
      • «• …» подряд — это список, и рисовать его должен клиент: собираем в
        <ul><li>. Раньше выходило восемь одинаковых абзацев с нарисованными
        точками — семь равноправных фактов вместо одного блока;
      • «🛑 <b>Germany-1</b> — …» — шапка объекта, а не рядовой факт: это строка
        узла со «Статуса сервиса» (точка состояния + имя). Поднимаем имя в
        надпись раздела, остальное оставляем абзацем — но ТОЛЬКО в той
        обстановке, ради которой правило вводилось (см. ниже);
      • всё прочее — обычный абзац, как было.
    """
    parts: list[str] = []
    bullets: list[str] = []

    # Шапку объекта нельзя определять по одной лишь форме строки: ровно так же
    # выглядит фраза, написанная руками, — рассылка и «написать пользователю»
    # шлют текст владельца как есть. Заголовок ЗАГЛАВНЫМИ там читается как чужие
    # слова: человек написал «💥 <b>Акция</b> — минус 30%», а получатель увидел
    # раздел «💥 АКЦИЯ». Поэтому смотрим на соседей: алерт нод — это либо
    # несколько таких строк подряд (по строке на ноду), либо строка, за которой
    # идут её буллеты. Одинокая фраза среди обычного текста остаётся абзацем.
    heads = [_OBJECT_HEAD_RE.match(line) for line in lines]

    def is_object_head(index: int) -> bool:
        if heads[index] is None:
            return False
        if index > 0 and heads[index - 1] is not None:
            return True  # вторая и следующие строки серии
        if index + 1 < len(lines):
            return heads[index + 1] is not None or bool(_BULLET_RE.match(lines[index + 1]))
        return False

    def flush() -> None:
        if bullets:
            parts.append("<ul>" + "".join(f"<li>{b}</li>" for b in bullets) + "</ul>")
            bullets.clear()

    for index, line in enumerate(lines):
        bullet = _BULLET_RE.match(line)
        if bullet:
            bullets.append(bullet.group("text"))
            continue
        flush()
        head = heads[index]
        if head is not None and is_object_head(index):
            icon = _repaint(head.group("icon"))
            name = head.group("name").strip()
            if _UPPERCASABLE_RE.match(name):
                name = name.upper()  # URL и хост заглавными не пишут
            parts.append(f"<h5>{icon} {name}</h5>")
            parts.append(f"<p>{head.group('rest').strip()}</p>")
            continue
        parts.append(f"<p>{line}</p>")
    flush()
    return parts


def _details_block(body: str) -> str:
    """Сворачиваемый блок для rich-разметки: <details> вместо цитаты.

    В rich у цитаты нет режима «свёрнута»: RichBlockBlockQuotation — это только
    текст и подпись, атрибут expandable Bot API там просто игнорирует (ошибки не
    даёт, но список раскроется целиком). Сворачивается в rich ровно <details>:
    без атрибута open он закрыт, разворачивается нажатием в самом сообщении.

    Первая строка тела — это <summary> (видно всегда), остальные — содержимое.
    Подпись сворачивалки жирной не делаем: жирный в кабинете — это вес заголовка,
    а не всё подряд. Зато выносим в неё счётчик — чтобы, не разворачивая, было
    видно, сколько там строк.

    Нумерацию «1. 2. 3.» рисует клиент через <ol>, руками её набивать не надо.
    Хвост списка («…и ещё 7 — весь список в админке») в <ol> попасть НЕ должен:
    он получил бы следующий номер и соврал бы — печатаем его тихой сноской.
    """
    # NB: <ol> клиент нумерует ВСЕГДА с единицы, поэтому список в блоке может
    # быть только один — см. flush() ниже.
    lines = [ln.strip() for ln in body.strip().splitlines() if ln.strip()]
    if not lines:
        return ""
    summary, rest = _drop_icon(_TAG_RE.sub("", lines[0])).strip(), lines[1:]
    if not rest:
        return f"<p>{summary}</p>"  # прятать нечего — обычный абзац

    inner: list[str] = []
    items: list[tuple[str, str]] = []  # (номер из текста, текст пункта)
    shown = 0
    hidden = 0
    listed = False  # список в блоке уже был

    def flush() -> None:
        nonlocal shown, listed
        if not items:
            return
        shown += len(items)  # пункт остаётся пунктом, как бы он ни был напечатан
        if listed:
            # Второй <ol> клиент пронумерует заново с единицы, и получится
            # «1, 2, …, 1» — список соврёт. Пункты после разрыва печатаем
            # обычными строками с их СОБСТВЕННЫМИ номерами из текста: нумерация
            # остаётся сквозной и настоящей.
            inner.extend(f"<p>{num}. {text}</p>" for num, text in items)
        else:
            listed = True
            inner.append("<ol>" + "".join(f"<li>{text}</li>" for _, text in items) + "</ol>")
        items.clear()

    for line in rest:
        numbered = _NUMBERED_RE.match(line)
        if numbered:
            items.append((numbered.group("num"), numbered.group("text")))
            continue
        flush()
        if _LIST_TAIL_RE.match(line):
            # «…и ещё N» — сноска, а не пункт списка. Заодно вытаскиваем из неё
            # число: вместе с показанными оно даёт честный счётчик в подписи.
            more = re.search(r"\d+", line)
            hidden += int(more.group()) if more else 0
            inner.append(f"<p><i>{line}</i></p>")
            continue
        inner.append(f"<p>{line}</p>")
    flush()

    # Счётчик у подписи имеет смысл только рядом с настоящим списком. Без единого
    # <li> «…за 5 минут ответа не было» — это просто первое число во фразе, и
    # рядом с заголовком появлялась выдуманная цифра «· 5».
    total = shown + hidden if listed else 0
    if total:
        summary = f"{summary} · {total}"
    return f"<details><summary>{summary}</summary>{''.join(inner)}</details>"


def build_rich_html(text: str, footer_label: str, logo: str = "") -> Optional[str]:
    """Переводит наш HTML-текст уведомления в rich-разметку.

    None — если структуру не распознали (тогда шлём как раньше).
    """
    if not text or not text.strip():
        return None

    # Неприкосновенные блоки убираем из текста до разбора — вернём их в конце.
    text, expandable = _take_expandable(text)

    title: Optional[str] = None
    # Пары держим по разделам, а не общим списком: в одном уведомлении бывают
    # «ID» платежа, «ID» пользователя и «ID» пригласителя, и без своего
    # заголовка значение читается как относящееся не к тому объекту.
    sections: list[_Section] = []
    # Только то, что было ДО первого раздела (хештег события и т.п.). Всё
    # остальное попадает в свой раздел и печатается на своём месте.
    paragraphs: list[str] = []
    # Текущий раздел ещё принимает строки. Закрывается по </blockquote>: новая
    # цитата без своего hdr-заголовка — это другой объект, а не продолжение
    # предыдущего (иначе «Причина» блокировки оказывалась под «👤 Пользователь»).
    section_open = False

    def open_section(heading: Optional[str]) -> _Section:
        nonlocal section_open
        section: _Section = (heading, [], [])
        sections.append(section)
        section_open = True
        return section

    def current_section() -> _Section:
        """Текущий раздел; безымянный заводим на лету."""
        return sections[-1] if section_open else open_section(None)

    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue

        opens_quote = line.startswith("<blockquote>")
        closes_quote = line.endswith("</blockquote>")
        line = line.removeprefix("<blockquote>").removesuffix("</blockquote>").strip()

        # Цитата без предшествующего hdr-заголовка — отдельный безымянный раздел.
        if opens_quote and not section_open:
            open_section(None)

        if line:
            row = _ROW_RE.match(line)
            heading = _TITLE_RE.match(line) if title is None else None
            subhead = _SUBHEAD_RE.match(line)
            if row:
                # Пару без значения не печатаем совсем: пустая ячейка ничего не
                # сообщает, но отнимает строку и расширяет колонку ключей.
                if not _is_blank(row.group("value")):
                    # Подпись и значение приводим к виду кабинета СРАЗУ, а не при
                    # печати: по ним считается ширина таблицы и ищется главное
                    # число, и мерить надо то, что реально увидит владелец.
                    key, value = row.group("key"), row.group("value")
                    current_section()[1].append(
                        (_key_label(key), _tidy_spaces(_key_value(key, value)))
                    )
            elif heading:
                title = heading.group("title")
            elif subhead:
                # Строка-подзаголовок вида «<b>🖥 Нода</b>:» открывает новый
                # раздел. Выбрасывать её нельзя: тогда пары разных объектов
                # сливаются в одну таблицу и уведомление начинает врать —
                # «ID» пригласителя выглядит как «ID» платежа.
                open_section(_plain(subhead.group("head")))
            elif not sections:
                paragraphs.append(line)
            else:
                # Свободная строка после пар — это уже другой блок (концовка
                # уведомления, «Требуется ручная проверка»): свой раздел, чтобы
                # текст не уехал выше таблицы, к которой он не относится.
                section = current_section()
                if section[1]:
                    section = open_section(None)
                section[2].append(line)

        if closes_quote:
            section_open = False

    # Таблица есть не всегда: алерты мониторинга — это фразы, а не пары
    # «ключ-значение». Такие уведомления тоже показываем в новом виде (логотип,
    # заголовок, футер со временем), просто абзацами. Пусто совсем — отдаём None,
    # и уведомление уходит как раньше.
    if (
        not any(rows or texts for _, rows, texts in sections)
        and not paragraphs
        and title is None
        and not expandable
    ):
        return None

    # Строка-хештег («#SubscriptionNewEvent») — это надзаголовок: в кабинете
    # mono-label стоит НАД крупным заголовком, а не под ним. Забираем ведущие
    # хештеги из абзацев ДО того, как отсюда возьмут запасной заголовок, —
    # иначе заголовком уведомления стал бы сам хештег.
    overline: list[str] = []
    while paragraphs and _HASHTAG_RE.match(_plain(paragraphs[0])):
        overline.append(paragraphs.pop(0))

    if title is None:
        if paragraphs:
            title = _TAG_RE.sub("", paragraphs.pop(0)).strip()
        elif overline:
            # Заголовка нет и взять его неоткуда: хештег возвращаем на место
            # обычной строкой. Надзаголовку не над чем стоять, а заголовком
            # хештег быть не должен — Telegram делает его ссылкой на поиск.
            paragraphs.extend(overline)
            overline.clear()
        # Подпись бренда (footer_label) заголовком не ставим НИКОГДА: это имя
        # отправителя, оно уже стоит в подвале. Раньше рассылка из одного
        # хештега приходила с заголовком «Begemot VPN» — уведомление выглядело
        # так, будто бренд и есть новость.
    if title is not None:
        title = _clean_title(title)

    # Есть ли в уведомлении хоть что-то, кроме заголовка.
    has_body = (
        any(rows or texts for _, rows, texts in sections)
        or bool(paragraphs)
        or bool(expandable)
    )

    now = datetime.now(timezone.utc)
    # Фолбэк-текст времени клиент, знающий <tg-time>, перерисует в своей локали,
    # поэтому подпись «UTC» в нём соврала бы. Формат — как в кабинете и в сводке.
    stamp = (
        f'<tg-time unix="{int(now.timestamp())}" format="dt">'
        f'{now.strftime("%d.%m %H:%M")}</tg-time>'
    )

    parts = []
    if logo:
        parts.append(f'<img src="{html_lib.escape(logo, quote=True)}"/>')
    # Хештег в шапке НЕ печатаем. В кабинете надзаголовок — мелкая тихая подпись
    # над заголовком, а Telegram делает из хештега яркую синюю ссылку: он стоял
    # перед заголовком и был самым громким элементом сообщения. Уносим в подвал —
    # поиск по хештегу продолжает работать, но он больше не спорит с заголовком.
    # <h3>, а не <h5>: в спецификации 1 — самый крупный размер, 6 — самый мелкий,
    # то есть <h5> заголовком не выглядел вовсе. В кабинете заголовок экрана —
    # самый крупный элемент, и иерархия трёхступенчатая: заголовок → надпись
    # раздела → подпись поля.
    if title is not None:
        if has_body:
            parts.append(f"<h3>{title}</h3>")
        elif len(_plain(title)) <= _TITLE_FITS:
            # Заголовок — единственное содержимое. Самый крупный размер здесь
            # незаслуженный: заголовку нечего возглавлять. Ступень ниже.
            parts.append(f"<h4>{title}</h4>")
        else:
            # …а длинная фраза (так приходят рассылка и «написать пользователю»)
            # самым крупным размером превращается в стену на весь экран.
            # Печатаем абзацем — ровно так, как её и писали.
            parts.append(f"<p>{title}</p>")
    parts.extend(_free_lines(paragraphs))

    # Был ли уже напечатан хоть один раздел: от него надо отбить следующий,
    # если у того нет собственной надписи (см. ниже).
    printed_section = False
    # Где в parts лежат надписи разделов и сколько разделов реально напечатано —
    # чтобы в конце убрать надпись, если раздел оказался единственным.
    label_positions: list[int] = []
    printed_count = 0

    for heading, rows, texts in sections:
        # Главное число раздела вынимаем ДО раскладки таблицы: в кабинете
        # StatCard — это тихая подпись и под ней крупное значение, а не строка
        # наравне со счётчиками. Заодно уходит перекос, из-за которого выручка
        # вылетала под таблицу просто потому, что не влезала в ячейку.
        hero: Optional[_Pair] = None
        rest_rows: list[_Pair] = []
        for pair in rows:
            if (
                hero is None
                and pair[0].lower() in _HERO_KEYS
                and _HAS_DIGIT_RE.search(_plain(pair[1]))
            ):
                hero = pair
            else:
                rest_rows.append(pair)

        table_rows, aside_rows = _split_rows(rest_rows)
        if not table_rows and not aside_rows and not texts and hero is None:
            continue  # раздел без данных: заголовок сам по себе ничего не говорит
        if heading:
            label_positions.append(len(parts))
            parts.append(f"<h5>{html_lib.escape(_section_label(heading))}</h5>")
        elif printed_section and not texts:
            # Раздел безымянный и начинается сразу со строк данных, а перед ним
            # уже был раздел. Рамок у таблиц больше нет (это был почерк чужого
            # бота), и две таблицы подряд читаются как ОДИН список строк: пары
            # второго объекта выглядят продолжением первого — ровно тот дефект,
            # ради которого разделы вообще завели. Свою границу раздел получает
            # от надписи; у безымянного её нет, поэтому ставим линию.
            #
            # Свободный текст (условие «not texts») отбивать не надо: абзац и
            # так не путается со строками таблицы, а лишняя линия перед
            # концовкой вроде «Требуется ручная проверка» только шумит.
            parts.append("<hr/>")
        # Свободные строки раздела идут перед его таблицей: в разделе они всегда
        # оказываются раньше пар (текст после пар открывает новый раздел).
        parts.extend(_free_lines(texts))
        if hero:
            # Подпись НАД значением — как в StatCard кабинета
            # (AdminDashboardPage.tsx): сначала тихая подпись, потом крупное
            # число. Наоборот число оставалось без имени до следующей строки.
            parts.append(f"<p><i>{html_lib.escape(hero[0])}</i></p>")
            parts.append(f"<h4>{hero[1]}</h4>")
        if table_rows:
            body = "".join(
                f"<tr><td>{html_lib.escape(key)}</td><td>{value}</td></tr>"
                for key, value in table_rows
            )
            # `bordered` — БЕЗ `striped`. Голая таблица читается сплошной кашей:
            # строки ничем не отделены (жалоба владельца 8 августа). Линии между
            # строками — единственный способ их разделить, который даёт Telegram:
            # CSS там нет, а «волосяную линию снизу», как в кабинете, задать
            # нечем. Зебру НЕ включаем: чередование фона и есть та деталь, по
            # которой вид узнавался как чужой.
            parts.append(f"<table bordered>{body}</table>")
        # Широкая пара идёт сразу под таблицей СВОЕГО раздела. Общей кучей в
        # конце уведомления она отрывалась от объекта, к которому относится.
        # Подпись тихая (курсив), значение моноширинное — это DetailRow кабинета,
        # где payment_id намеренно приглушён, а не подан как заголовок раздела.
        parts.extend(
            f"<p><i>{html_lib.escape(key)}</i> {_aside_value(value)}</p>"
            for key, value in aside_rows
        )
        printed_section = True
        printed_count += 1
    # Сворачиваемые блоки — после таблицы: сначала цифры, потом расшифровка.
    parts.extend(block for block in map(_details_block, expandable) if block)

    # Раздел в сообщении один — его надпись убираем. «ПОЛЬЗОВАТЕЛЬ» под
    # заголовком «Новый пользователь» ничего не добавляет: заголовок уже сказал,
    # о чём речь. Надписи нужны ТОЛЬКО чтобы различать несколько объектов в одном
    # сообщении (платёж / пользователь / тариф). На двух строках данных пять
    # блоков обрамления давали экран воздуха — жалоба владельца 8 августа.
    if printed_count == 1 and len(label_positions) == 1:
        del parts[label_positions[0]]

    # Линия перед подвалом — только когда телу есть что отделять. У короткого
    # уведомления (один раздел, без свёрнутых блоков) подвал и так отбит, а
    # лишняя линия — ещё одна пустая строка.
    if printed_count > 1 or expandable:
        parts.append("<hr/>")
    tail = " · ".join([*(_plain(tag) for tag in overline), html_lib.escape(footer_label)])
    parts.append(f"<footer>{tail} · {stamp}</footer>")
    return "".join(parts)


async def send_rich_message(
    bot: Bot,
    chat_id: int,
    rich_html: str,
    reply_markup: Any = None,
    disable_notification: Optional[bool] = None,
) -> Optional[int]:
    """Шлёт rich-сообщение через Bot API.

    Возвращает message_id отправленного сообщения; None — не вышло, шлите обычным
    путём. Именно message_id, а не «да/нет»: вызывающему он нужен и чтобы вернуть
    наверх настоящий Message («доставлено»), и чтобы завести автоудаление.
    """
    if not rich_enabled():
        return None

    payload: dict[str, Any] = {
        "chat_id": chat_id,
        "rich_message": {"html": rich_html},
    }
    if reply_markup is not None:
        payload["reply_markup"] = reply_markup.model_dump(exclude_none=True)
    if disable_notification is not None:
        payload["disable_notification"] = disable_notification

    url = bot.session.api.api_url(token=bot.token, method="sendRichMessage")

    try:
        session = await bot.session.create_session()
        async with session.post(url, json=payload) as response:
            status = response.status
            data = await response.json()
    except Exception as exc:  # noqa: BLE001 — сеть/парсинг: молча падаем на обычный вид
        logger.warning(f"[OVERLAY] rich-отправка не удалась ({exc}) — обычный вид")
        return None

    if data.get("ok"):
        result = data.get("result")
        message_id = result.get("message_id") if isinstance(result, dict) else None
        # Telegram всегда отдаёт id отправленного сообщения. Если его вдруг нет —
        # 0: «доставлено, но id неизвестен». Повторять отправку нельзя (владелец
        # получит дубль), просто не будет автоудаления.
        return message_id if isinstance(message_id, int) else 0

    description = str(data.get("description", ""))
    lowered = description.lower()
    # Латч «сервер метода не знает» взводится НАВСЕГДА (до перезапуска), поэтому
    # взводить его можно только на настоящий признак отсутствия метода. Проверено
    # на живом Bot API:
    #   неизвестный метод  -> 404 «Not Found»
    #   недостижимый чат   -> 400 «Bad Request: chat not found»
    # Раньше сюда проходил любой «not found», и первый же админ без чата с ботом
    # выключал rich-вид всему процессу, а в лог уходило враньё про поддержку
    # метода. Недоставка получателю — обычный отказ: None, но БЕЗ латча.
    recipient_gone = any(
        marker in lowered
        for marker in ("chat not found", "user not found", "peer_id_invalid")
    )
    if status == 404 and not recipient_gone:
        _mark_unavailable(description or "404")
        return None

    logger.warning(f"[OVERLAY] rich-отправка отклонена: {description} — обычный вид")
    return None
