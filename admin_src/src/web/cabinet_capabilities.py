"""Что из нужного кабинету умеет ЭТОТ бот.

ЗАЧЕМ. Кабинет бывает новее бота: оператор обновил только кабинет
(`./update.sh --cabinet-only`) или кабинет стоит на отдельном сервере. Тогда разделы,
которым нужен код нового бота, кабинет прячет, а не показывает кнопки, упирающиеся
в 404, и тумблеры, которые «сохраняются», а бот молча выбрасывает поле. Список уходит
в GET /api/v1/public/appearance полем `bot_capabilities`; бот без поля (1.3.8 и
старше) кабинет считает ботом без единого токена.

ПОЧЕМУ СПИСОК, А НЕ НОМЕР ВЕРСИИ. VERSION поднимается только при выпуске, а код на
бой уходит раньше; на установке с локальной HA-копией файл VERSION ещё и
примонтирован с хоста — после «только кабинет» старый код видел бы новый номер.
Список лежит в коде бота и меняется в том же коммите, что и ручка, поэтому не врёт.
Номер версии наружу не отдаём вовсе: по нему удобно подбирать известные дыры.

ПРАВИЛА.
  * Токен добавляется В ТОМ ЖЕ коммите, что и код бота, от которого зависит кабинет,
    и одновременно — запись в cabinet/src/lib/botCapabilities.ts (vitest сверяет
    оба файла). Когда токен обязателен — см. шапку botCapabilities.ts.
  * Токен не удаляется, пока кабинет на него смотрит.
  * ФОРМАТ СТРОК НЕ МЕНЯТЬ: update.sh читает этот файл из образа работающего бота
    sed'ом (`    "токен",` и `    "токен": "подпись",`). Формат заперт
    tests/test_cabinet_capabilities.py.
"""

# Возможности, от которых зависит КАБИНЕТ. Публичные: то же самое снаружи видно по
# 401 против 404 на админских путях, нового знания список не даёт.
CABINET_CAPABILITIES: tuple[str, ...] = (
    "bulk_jobs",
    "renewal_discount",
    "device_upsell",
    "broadcast_expiring",
    "digest_email",
    "refunds_tile",
    "ad_link_url",
    "plan_change_carry",
    "extra_device",
    "extra_traffic",
)

# Заметные изменения ТОЛЬКО в боте — кабинета не касаются, но при «только кабинет»
# они не устанавливаются, и итог update.sh должен назвать их поимённо. Наружу НЕ
# отдаются: список исправлений бота — это отпечаток версии, тот же номер версии
# другими словами. Подпись — для человека, читающего вывод update.sh.
BOT_ONLY_CHANGES: dict[str, str] = {
    "expiry_reminders_3x": "Напоминания об окончании подписки на панели Remnawave 3.x",
    "device_webhooks_3x": "Уведомления о новых и удалённых устройствах на панели Remnawave 3.x",
}


def public_capabilities() -> list[str]:
    """Значение поля `bot_capabilities` в публичном оформлении.

    Отдельной функцией, а не строкой в ручке: ручка обёрнута DI-контейнером, и тест
    без поднятого контейнера проверяет здесь, что наружу уходит ровно кабинетный
    список — и ни одного токена из BOT_ONLY_CHANGES.
    """
    return list(CABINET_CAPABILITIES)
