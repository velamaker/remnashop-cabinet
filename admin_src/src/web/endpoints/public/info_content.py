def normalize_lang(lang: Any) -> Optional[str]:
    """«EN» → «en»; всё, что не двухбуквенный код, — None (значит русский)."""
    code = str(lang or "").strip().lower()
    return code if len(code) == 2 and code.isalpha() else None

