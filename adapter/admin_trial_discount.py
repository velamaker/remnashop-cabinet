# --- память о выданных предложениях ----------------------------------------------

# Сколько храним отметку. Внутри пробного периода повтор невозможен и без срока —
# ключ отметки привязан к самой пробной подписке. Срок нужен от другого: отметки
# лежат ОДНОЙ записью JSON в общей памяти (своих таблиц нам заводить нельзя), и
# вечный список рано или поздно превратит каждую отправку в перезапись мегабайта.
# Год с лишним — заведомо больше любого триала и любого разумного спора о нём.
_MARK_TTL_DAYS = 400


def _mark_key(user_id: int, trial_id: Any) -> str:
    """Ключ отметки: человек + его пробная подписка.

    Не просто id человека: «одно предложение за пробный период» — это про
    конкретный триал. Если у подписки почему-то нет id (чужая сборка отдала
    урезанный ответ), падаем на ключ по человеку — тогда предложение будет ровно
    одно на всю его жизнь, и это безопасная сторона ошибки.
    """
    try:
        return f"{int(user_id)}:{int(trial_id)}"
    except (TypeError, ValueError):
        return f"{int(user_id)}:-"


# Хвост отметки. Без хвоста «YYYY-MM-DD» — предложение ВЫДАНО (так писали
# раньше, старые записи читаются как были). С хвостом это память о НЕУДАЧЕ:
#   «YYYY-MM-DD!x» — доставить нельзя никогда (бот заблокирован, телеграма нет);
#   «YYYY-MM-DD!3» — три неудачные попытки, четвёртая ещё будет.
# Одна строка вместо второй записи в хранилище: файл базы общий, и заводить ради
# счётчика попыток вторую таблицу нам нельзя.
_MARK_FAIL = "!"
_MARK_NEVER = "!x"


def _mark_state(value: Any) -> tuple[str, int]:
    """Отметка → («sent» | «never» | «tries» | «», сколько попыток было)."""
    text = str(value or "").strip()
    if not text:
        return "", 0
    if _MARK_FAIL not in text:
        return "sent", 0
    tail = text.split(_MARK_FAIL, 1)[1]
    if tail == "x":
        return "never", 0
    try:
        return "tries", int(tail)
    except ValueError:
        # Непонятный хвост — считаем выданным: лишний раз промолчать дешевле,
        # чем прислать человеку второе предложение.
        return "sent", 0


def _marks(state: Any) -> dict[str, str]:
    """Что уже было по паре «человек + его триал»: дата выдачи (YYYY-MM-DD) или
    та же дата с хвостом неудачи. Протухшее отбрасываем при чтении, чтобы запись
    не росла бесконечно."""
    if state is None or not getattr(state, "available", False):
        return {}
    raw = state.get_setting(_MARK_KEY, {})
    if not isinstance(raw, dict):
        return {}
    edge = (datetime.now(timezone.utc) - timedelta(days=_MARK_TTL_DAYS)).strftime("%Y-%m-%d")
    out: dict[str, str] = {}
    for key, value in raw.items():
        # Значение храним ЦЕЛИКОМ (раньше резалось до десяти символов — и хвост
        # неудачи терялся бы при первом же чтении), а для срока смотрим на дату в
        # его начале. Даты пишем одним форматом (ISO-дата), поэтому сравнение
        # строк здесь равносильно сравнению дат. Непонятную запись держим:
        # потерять отметку хуже, чем хранить лишнюю — потеря означает второе
        # письмо человеку.
        text = str(value or "").strip()
        if len(text) >= 10 and text[:10] < edge:
            continue
        name = str(key or "").strip()
        if name and text:
            out[name] = text
    return out


def _save_marks(state: Any, marks: dict[str, str]) -> None:
    if state is None or not getattr(state, "available", False):
        return
    state.set_setting(_MARK_KEY, marks)


def _mark_failure(
    state: Any, marks: dict[str, str], key: str, now: datetime, forever: bool
) -> str:
    """Запомнить неудачу доставки. Возвращает новое значение отметки.

    Пишем сразу, как и отметку об удаче: контейнер перезапускают при каждом
    обновлении, а «сохраним в конце прогона» здесь означало бы, что счётчик
    попыток обнуляется чаще, чем растёт, и заблокировавший бота человек снова
    получает свои сотни выпущенных-и-отозванных кодов.
    """
    _kind, tries = _mark_state(marks.get(key))
    tail = _MARK_NEVER if forever else f"{_MARK_FAIL}{min(tries + 1, _MAX_TRIES)}"
    marks[key] = now.strftime("%Y-%m-%d") + tail
    _save_marks(state, marks)
    return marks[key]


# --- невручённые коды, которые не удалось убрать ------------------------------------

# Отзыв кода может не пройти (бот лёг ровно между отправкой и удалением). Раньше
# про это знал только лог, а живые коды на скидку тихо копились в админке
# владельца. Держим список — его показывает холостой прогон, чтобы владелец мог
# убрать их руками. Список короткий: это не журнал, а напоминание.
_ORPHAN_KEY = "trial_discount_orphans"
_ORPHAN_LIMIT = 50


def _orphans(state: Any) -> list[dict[str, Any]]:
    """Невручённые коды, которые ещё живы. Сгоревшие по сроку не показываем: они
    уже никому не достанутся, и напоминать о них незачем."""
    if state is None or not getattr(state, "available", False):
        return []
    raw = state.get_setting(_ORPHAN_KEY, [])
    rows = [r for r in raw if isinstance(r, dict)] if isinstance(raw, list) else []
    now = datetime.now(timezone.utc)
    alive = []
    for row in rows:
        until = _stamp(row.get("valid_until"))
        if until is None or until > now:
            alive.append(row)
    return alive


def _remember_orphan(state: Any, issued: dict[str, Any], reason: str) -> None:
    if state is None or not getattr(state, "available", False):
        return
    rows = _orphans(state)
    rows.insert(
        0,
        {
            "id": issued.get("id"),
            "code": issued.get("code"),
            "valid_until": issued.get("valid_until"),
            "at": datetime.now(timezone.utc).isoformat(),
            "reason": reason,
        },
    )
    state.set_setting(_ORPHAN_KEY, rows[:_ORPHAN_LIMIT])


