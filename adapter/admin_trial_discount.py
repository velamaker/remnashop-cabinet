@_claim("PUT", "/api/admin/trial-discount")
async def trial_discount_save(ctx: Ctx) -> dict[str, Any]:
    """Сохранение. Меняем только присланное — экран шлёт частичное обновление.

    Включить, когда выдать или доставить нечем, нельзя: тумблер «включено» при
    молчащей рассылке — ложь в админке, которую замечают через месяц по вопросу
    «а где обещанные покупки». Отказ приходит ДО записи, и сохранение не проходит
    целиком: «часть настроек применилась, часть нет» после ошибки — худший из
    возможных исходов. Проценты и сроки настраиваются обычным сохранением с
    выключенным тумблером.

    ПРО ПРАВА И ПРО «СТОП». Право на рассылку (`users:send_message`) спрашиваем
    только у того, кто ВКЛЮЧАЕТ раздачу или меняет её условия при включённой.
    Раньше проверка стояла до чтения тела — и «стоп» оказывался защищён строже,
    чем «пуск»: админ, у которого право отобрали, не мог погасить уже идущую
    раздачу скидок, а другого выключателя тут нет. Выключение обязано проходить
    всегда: это тормоз, а не рычаг.
    """
    await _require_admin(ctx)
    if ctx.state is None or not ctx.state.available:
        raise NotAvailable(
            "Настройку некуда сохранить: у адаптера нет доступа к своему хранилищу"
        )

    body = ctx.payload()
    enabled = body.get("enabled")
    config = _config(ctx.state)

    # Что в теле реально МЕНЯЕТ настройку. Экран всегда шлёт все четыре поля, и
    # без этого сравнения «выключить» неотличимо от «поменять условия».
    changes: dict[str, int] = {}
    for field, low, high in (
        ("percent", _PERCENT_MIN, _PERCENT_MAX),
        ("days_before", _DAYS_MIN, _DAYS_MAX),
        ("lifetime_hours", _HOURS_MIN, _HOURS_MAX),
    ):
        if body.get(field) is not None:
            value = _clamp(body[field], int(config[field]), low, high)
            if value != int(config[field]):
                changes[field] = value

    turning_on = enabled is not None and bool(enabled)
    # Каким тумблер станет ПОСЛЕ сохранения: молчание в теле означает «как было».
    will_run = bool(enabled) if enabled is not None else bool(config["enabled"])
    if will_run and (turning_on or changes):
        # Право спрашиваем только там, где после сохранения кому-то уйдут письма
        # со скидками. Выключение и правка цифр при погашенном тумблере проходят
        # по одному `_require_admin`: остановка не должна упираться в право,
        # которого у человека может уже не быть, а настройка, из которой ничего
        # не уходит, никому не вредит.
        await _require_send_right(ctx)

    if turning_on:
        if not _delivery_configured():
            raise NotAvailable(bot_session.NO_DELIVERY)
        if not ctx.can_admin:
            raise NotAvailable(
                "Скидку триальщикам включить нечем: без машинного ключа бота "
                "(BEDOLAGA_ADMIN_TOKEN) адаптер не видит, у кого кончается "
                "пробный период, и не может убрать невручённый промокод."
            )

    config.update(changes)
    if enabled is not None:
        config["enabled"] = bool(enabled)

    ctx.state.set_setting(_KEY, config)
    return _with_note(config)


@_claim("POST", "/api/admin/trial-discount/dry-run", deadline=120.0)
async def trial_discount_dry_run(ctx: Ctx) -> dict[str, Any]:
    """Холостой прогон: кому предложим скидку и каким текстом — без выдачи и отправки.

    Нужен потому, что проверить такую рассылку иначе можно единственным способом —
    раздать живым людям настоящие скидки. Здесь не выпускается ни одного
    промокода, не отправляется ни одного сообщения и не ставится ни одной
    отметки, поэтому звать её безопасно хоть подряд. Выключенный тумблер её не
    блокирует: посмотреть, кого зацепит, до включения — ровно то, ради чего она и
    нужна.

    `user_id` (в теле или в query) — посмотреть одного человека вместе с причиной
    отказа. Без него берётся первая горстка (_DRY_LIMIT).

    ПРАВО СПРАШИВАЕМ ОТДЕЛЬНО. Ответ этой ручки — данные ЛЮДЕЙ: id, telegram_id,
    язык, дата конца пробного, а `user_id` позволяет смотреть их по одному без
    всякого потолка. Сам бот такой список закрывает правом `users:read`
    (`routes/admin_users.py`), а данные мы берём машинным ключом, у которого прав
    всегда полный набор. Одного `is_admin` тут мало: он у них истинен любому с
    ролью уровня выше нуля — например штатному «Marketer», у которого нет ни
    одного права на людей. Без этой проверки наш экран стал бы дырой в ИХ RBAC.
    """
    await _require_admin(ctx)
    await _require_right(ctx, _READ_RIGHT)
    raw = ctx.payload().get("user_id", ctx.query.get("user_id"))
    only: int | None = None
    if raw not in (None, ""):
        try:
            only = int(raw)
        except (TypeError, ValueError):
            raise _fail(400, "user_id должен быть числом") from None

    config = _config(ctx.state)
    summary = await run_once(
        ctx, config, dry_run=True, only_user_id=only, limit=None if only else _DRY_LIMIT
    )
    summary["config"] = config
    summary["quiet_hours"] = f"{_QUIET_FROM}:00–{_QUIET_TO}:00"
    summary["delivery_configured"] = _delivery_configured()
    summary["can_issue_discount"] = ctx.can_admin
    # Честно про способ выдачи: скидка не появляется у человека сама — он вводит
    # присланный промокод. Владелец должен узнать это из ответа ручки, а не из
    # вопроса «почему у триальщика не горит баннер скидки».
    summary["discount_mechanism"] = (
        "одноразовый промокод «Бедолаги» на процентную скидку с их признаком "
        "«только первая покупка»: человек вводит его в кабинете или в боте, после "
        "чего скидка появляется на аккаунте и загорается баннер. К человеку код не "
        "привязан — поля «кому» у промокода нет, поэтому пересланный код "
        "активирует любой, кто ещё не платил. Выпускается кабинетной ручкой бота "
        f"от имени служебного админа: ему нужны права «{_SEND_RIGHT}» и "
        f"«{_ISSUE_RIGHT}»."
    )
    if not summary["delivery_configured"]:
        summary["delivery_note"] = bot_session.NO_DELIVERY
    if not summary["can_issue_discount"]:
        summary["discount_note"] = (
            "Без машинного ключа бота (BEDOLAGA_ADMIN_TOKEN) адаптер не увидит "
            "триальщиков и не сможет убрать невручённый промокод."
        )
    # Когда окно выдачи длиннее жизни кода, срок кода тянется до конца пробного
    # (иначе предложение умирало бы раньше, чем человек решится). Владельцу это
    # надо сказать: он выставил 72 часа, а в сообщении увидит другую дату.
    if int(config["days_before"]) * 24 > int(config["lifetime_hours"]):
        summary["lifetime_note"] = (
            "Окно выдачи ({days} дн.) длиннее срока жизни промокода ({hours} ч.), "
            "поэтому код будет жить до конца пробного периода человека — иначе он "
            "гас бы раньше, чем этот период кончится.".format(
                days=int(config["days_before"]), hours=int(config["lifetime_hours"])
            )
        )
    # Невручённые коды, которые не удалось убрать: живая скидка «на предъявителя»
    # у них в админке. Показываем здесь, потому что лог владелец не читает.
    orphans = _orphans(ctx.state)
    if orphans:
        summary["orphan_codes"] = orphans[:10]
        summary["orphan_note"] = (
            f"Не удалось убрать невручённых промокодов: {len(orphans)}. Они живы и "
            "их может активировать любой, кому попадутся, — удалите их в разделе "
            "промокодов бота."
        )
    return summary
