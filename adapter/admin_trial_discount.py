def _claim(method: str, path: str, deadline: float | None = None) -> Any:
    """Регистрирует наш обработчик, но НЕ отбирает уже занятый путь.

    Правило, заработанное кровью: наши модули грузятся ПОСЛЕДНИМИ и молча
    перехватывают чужой слот (`compose.handler` просто перезаписывает запись в
    HANDLERS). Так промо-баннер однажды отобрал у «Бедолаги» её персональные
    офферы, и люди перестали их видеть. Если путь занят — значит у бота эта
    функция своя, и правильный ответ «оставить как было и сказать вслух», а не
    «поставить своё поверх».
    """
    owner = HANDLERS.get((method.upper(), path))
    if owner is not None:
        _log(
            f"путь {method} {path} уже обслуживается ботом — свой обработчик не "
            "ставим, чтобы не отобрать у него готовую функцию"
        )
        return lambda fn: fn
    return handler(method, path, deadline=deadline)


