async def _require_admin(ctx: Ctx) -> None:
    """Порог входа: администратор бота.

    Эта ручка не ходит в их API за данными, а читает своё хранилище, поэтому
    права обязана спросить явно: иначе настройку кабинета видел бы любой, кто
    знает путь.

    ВАЖНО, ЧЕГО ЭТА ПРОВЕРКА НЕ ЗНАЧИТ. `is-admin` у них отвечает `true` любому,
    у кого есть активная роль уровня выше нуля (`routes/auth.py:2065-2080`), — в
    том числе штатному «Marketer», у которого нет ни одного права `users:*`.
    Поэтому она годится только как порог, а всё, что показывает или трогает
    ЛЮДЕЙ, обязано спросить конкретное право отдельно (`_require_right`).
    """
    if not ctx.token:
        raise _fail(401, "Требуется вход")
    me = await ctx.json("/cabinet/auth/me/is-admin", {}, soft=True) or {}
    if not me.get("is_admin"):
        raise _fail(403, "Недостаточно прав")


async def _require_right(ctx: Ctx, right: str) -> None:
    """Спросить у их RBAC конкретное право зашедшего админа.

    Сравнение по их правилу — право пользователя это ШАБЛОН (`*:*`, `users:*`).
    Не смогли спросить — считаем, что права нет: тихо разрешить дороже, чем зря
    отказать.
    """
    data = await ctx.json("/cabinet/auth/me/permissions", {}, soft=True) or {}
    granted = data.get("permissions")
    ok = isinstance(granted, list) and any(
        isinstance(p, str) and fnmatchcase(right, p) for p in granted
    )
    if not ok:
        raise _fail(403, f"Недостаточно прав в боте: нужно право «{right}»")


async def _require_send_right(ctx: Ctx) -> None:
    """Включать рассылку и менять её условия может тот, кому их RBAC разрешает
    писать людям.

    Сохранение здесь — не «поправить текст на экране», а включение рассылки
    личных сообщений от имени их бота, да ещё и с выдачей скидок. Право на
    рассылку у них уже есть (`users:send_message`), поэтому спрашиваем его, а не
    выдумываем своё: админ «только для просмотра» не должен уметь раздать скидку
    всем триальщикам.
    """
    await _require_right(ctx, _SEND_RIGHT)


