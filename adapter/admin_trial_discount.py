async def _bot_users(ctx: Ctx) -> list[dict[str, Any]]:
    """Люди бота: кому писать, под каким id и что у них с пробным периодом.

    Берём машинным ключом (`ctx.admin`) — это единственный доступ, который есть у
    фоновой задачи. Ошибку не проглатываем: пустой список молча означал бы «на
    пробном никого нет», а это неправда.

    Конец списка определяем ТОЛЬКО по короткой странице. Поле `total` в их ответе
    доверия не заслуживает: на живом стенде оно равно 1 при семи пользователях
    (проверено запросом), и остановка по нему обрезала бы рассылку после первой
    страницы.
    """
    if not ctx.can_admin:
        raise RuntimeError(
            "адаптеру не выдан машинный ключ бота (BEDOLAGA_ADMIN_TOKEN) — "
            "ни список триальщиков, ни выпуск промокода без него невозможны"
        )
    out: list[dict[str, Any]] = []
    offset = 0
    for _ in range(_PAGES_LIMIT):
        resp = await ctx.admin(
            "GET", "/users", params={"limit": _BOT_PAGE, "offset": offset}
        )
        if resp is None:
            raise RuntimeError("бот недоступен: список пользователей не получен")
        if resp.status_code >= 400:
            raise RuntimeError(f"бот отказал в списке пользователей: {_detail(resp)}")
        try:
            data = resp.json() or {}
        except ValueError as exc:
            raise RuntimeError("бот ответил не-JSON на список пользователей") from exc
        batch = data.get("items") or []
        if not isinstance(batch, list) or not batch:
            break
        out.extend(x for x in batch if isinstance(x, dict))
        offset += len(batch)
        if len(batch) < _BOT_PAGE:
            break
    return out


# Состояния подписки, при которых пробный период считается живым. `actual_status`
# у них считается на лету (`Subscription.actual_status`) и уже учитывает, что
# срок вышел; `disabled`/`limited`/`expired` — не наш случай.
_ALIVE = ("active", "trial")


def _trial(user: dict[str, Any], now: datetime) -> dict[str, Any] | None:
    """Пробная подписка человека — ЖИВАЯ и ближайшая к концу.

    Смотрим и текущую (`subscription`), и весь список (`subscriptions`): в
    мульти-тарифном режиме подписок у человека несколько, и триал может быть не
    «текущим».

    ПОЧЕМУ ЖИВАЯ, А НЕ ПРОСТО БЛИЖАЙШАЯ. Их `/users` отдаёт ВСЕ строки подписок
    без фильтра, включая давно протухшие, и «ближайшая к концу» из них — всегда
    мёртвая. Человек с живым триалом до завтра, у которого рядом лежит
    прошлогодний триал, получал вердикт «пробный период не активен (expired)» и
    выпадал из рассылки навсегда — притом что окно как раз наступило. Поэтому
    сначала отбираем живые, и только если живых нет вовсе, возвращаем самую
    ПОЗДНЮЮ из мёртвых — ради честного вердикта на экране («истёк такого-то»), а
    не ради выдачи.
    """
    rows = list(user.get("subscriptions") or [])
    current = user.get("subscription")
    if isinstance(current, dict):
        rows.append(current)

    alive: dict[str, Any] | None = None
    alive_end: datetime | None = None
    last: dict[str, Any] | None = None
    last_end: datetime | None = None
    for row in rows:
        if not isinstance(row, dict) or not row.get("is_trial"):
            continue
        end = _stamp(row.get("end_date"))
        if end is None:
            continue
        status = str(row.get("actual_status") or row.get("status") or "").lower()
        if status in _ALIVE and end > now:
            if alive_end is None or end < alive_end:
                alive, alive_end = row, end
        if last_end is None or end > last_end:
            last, last_end = row, end
    return alive or last


def _examine(
    users: list[dict[str, Any]],
    marks: dict[str, str],
    config: dict[str, Any],
    now: datetime,
) -> list[dict[str, Any]]:
    """Вердикт по каждому человеку — до единого обращения наружу.

    Чистая функция: сюда приходят готовые списки, отсюда уходит решение. Так его
    видно на глаз и можно проверить без единой отправки и без единого выданного
    промокода. Причина отказа не выбрасывается, а едет дальше: холостой прогон
    показывает владельцу, почему конкретный человек остался без предложения.
    """
    days_before = int(config["days_before"])
    edge = now + timedelta(days=days_before)

    out: list[dict[str, Any]] = []
    for user in users:
        try:
            uid = int(user.get("id"))
        except (TypeError, ValueError):
            continue
        trial = _trial(user, now)
        end = _stamp(trial.get("end_date")) if trial else None
        status = str((trial or {}).get("actual_status") or (trial or {}).get("status") or "").lower()
        key = _mark_key(uid, (trial or {}).get("id"))
        record: dict[str, Any] = {
            "user_id": uid,
            "telegram_id": user.get("telegram_id"),
            "language": str(user.get("language") or "ru")[:2].lower(),
            "trial_ends": end.isoformat() if end else None,
            "mark_key": key,
            "skip": "",
        }
        out.append(record)

        if str(user.get("status") or "").lower() != "active":
            # Заблокированным и удалённым «купите со скидкой» — издевательство:
            # купить им всё равно не дадут.
            record["skip"] = "аккаунт не активен"
        elif trial is None or end is None:
            record["skip"] = "нет пробного периода"
        elif status not in _ALIVE:
            # Подписка есть, но она уже не живая (истекла, отключена, упёрлась в
            # лимит). Предлагать «успейте до конца пробного» тут поздно и неправда.
            record["skip"] = f"пробный период не активен ({status or 'статус неизвестен'})"
        elif end <= now:
            record["skip"] = "пробный период уже кончился"
        elif end > edge:
            record["skip"] = f"до конца пробного больше {days_before} дн."
        elif user.get("has_had_paid_subscription"):
            # Смысл раздела — скидка на ПЕРВУЮ покупку. Тот, кто уже платил,
            # получил бы подарок ни за что: деньги владельца, не наши.
            record["skip"] = "уже покупал подписку"
        elif not user.get("telegram_id"):
            # Канал один — личное сообщение бота. Промокод, о котором некому
            # рассказать, — мусор в их админке, поэтому и не выпускаем.
            record["skip"] = "нет телеграма"
        elif key in marks:
            kind, tries = _mark_state(marks[key])
            day = str(marks[key])[:10]
            if kind == "never":
                # Их приговор, а не наша догадка: бот заблокирован или телеграма
                # нет вовсе. Повторять — это выпускать и тут же удалять код
                # каждый час до конца окна.
                record["skip"] = "доставить нельзя: бот заблокирован (проверено)"
            elif kind == "tries" and tries >= _MAX_TRIES:
                record["skip"] = f"не доставлено {tries} раз подряд — больше не пробуем"
            elif kind != "tries":
                record["skip"] = f"предложение уже выдавали {day}"
            # kind == "tries" и попытки не исчерпаны — человек остаётся
            # кандидатом: беда могла быть часовой.
    return out


# --- скидка их средствами -----------------------------------------------------------


def _new_code() -> str:
    """Одноразовый код для одного человека. Случайный, а не «TRIAL15»:
    предсказуемый код увели бы у того, кому он выдан."""
    body = "".join(secrets.choice(_CODE_ALPHABET) for _ in range(_CODE_BODY))
    return f"{_CODE_PREFIX}{body}"


def _deadline(now: datetime, hours: int, trial_end: datetime | None) -> datetime:
    """Докуда код можно активировать.

    НЕ просто «сейчас + срок жизни». `days_before` и `lifetime_hours` на экране
    независимы, и их сочетание разрешено любое: при `days_before = 7` и
    `lifetime_hours = 72` код умирал бы за четверо суток ДО конца пробного, а
    сообщение противоречило само себе — «ваш пробный кончается 10-го, введите код
    до 6-го». Человек получал предложение, мёртвое к моменту решения о покупке.

    Правило простое и объяснимое: код живёт `lifetime_hours`, но не гаснет
    раньше самого триала, ради которого выдан. Кому нужен запас ПОСЛЕ конца
    пробного — увеличивает `lifetime_hours`, он и так считается от выдачи.
    """
    base = now + timedelta(hours=hours)
    return trial_end if trial_end is not None and trial_end > base else base


async def _issue_code(
    ctx: Ctx, percent: int, hours: int, deadline: datetime
) -> dict[str, Any]:
    """Выпускает одноразовый промокод на скидку. Возвращает их запись о нём.

    ЧЕМ ВЫПУСКАЕМ. Их КАБИНЕТНОЙ ручкой от имени служебного админа, а не машинным
    ключом: только у неё есть `first_purchase_only`, то есть их собственная
    проверка «этот код не для тех, кто уже платил». Без неё код был бы «на
    предъявителя» — пересланный, он дал бы скидку ровно той категории, которую
    раздел сознательно исключает при отборе. Цена выбора названа в шапке файла:
    служебному админу нужно право `promocodes:create`.

    Тип `discount` у них переиспользует поля: `balance_bonus_kopeks` — это
    ПРОЦЕНТ, а `subscription_days` — ЧАСЫ жизни скидки после активации (см.
    `promocode_service._apply_promocode_effects`). Не копейки и не дни; передать
    сюда рубли значило бы выдать скидку в тысячи процентов.

    Про два срока. `deadline` (`valid_until`) — докуда можно активировать код,
    `hours` — сколько живёт уже активированная скидка. Первый считает `_deadline`
    с оглядкой на конец триала, второй — ровно настройка владельца. Плата за
    простоту: активировав код в последний час, человек получит скидку ещё на
    полный срок; растянуть её ровно до общего дедлайна их модель не умеет (часы
    фиксируются при выпуске).

    Отказ бота не глотаем: выданная «наполовину» скидка хуже отсутствующей. И
    любой отказ здесь — беда ВСЕГО прогона (нет прав, ключ, бот лежит), а не
    одного человека: разбирается с этим вызывающий.
    """
    last = ""
    for _ in range(_CODE_TRIES):
        code = _new_code()
        try:
            resp = await bot_session.request(
                ctx,
                "POST",
                "/cabinet/admin/promocodes",
                json={
                    "code": code,
                    "type": "discount",
                    "balance_bonus_kopeks": int(percent),
                    "subscription_days": int(hours),
                    "max_uses": 1,
                    "valid_until": deadline.isoformat().replace("+00:00", "Z"),
                    "is_active": True,
                    # Их собственная защита: при активации бот сам откажет тому, у
                    # кого уже была платная подписка (`not_first_purchase`).
                    "first_purchase_only": True,
                },
            )
        except httpx.HTTPError as exc:
            raise RuntimeError(f"бот недоступен: промокод не выпущен ({exc})") from exc
        if resp.status_code < 400:
            try:
                data = resp.json() or {}
            except ValueError as exc:
                raise RuntimeError("бот ответил не-JSON на выпуск промокода") from exc
            if not data.get("first_purchase_only"):
                # Их ответ говорит, что защита не легла (чужая сборка, где поле
                # игнорируется). Молчать нельзя: код без неё раздаёт скидку тем,
                # кто уже платил, — деньги владельца.
                _log(
                    f"промокод {data.get('code') or code} выпущен БЕЗ признака "
                    "«только первая покупка» — бот его не принял"
                )
            return {
                "id": data.get("id"),
                "code": str(data.get("code") or code),
                "valid_until": data.get("valid_until") or deadline.isoformat(),
                "first_purchase_only": bool(data.get("first_purchase_only")),
            }
        if resp.status_code in (401, 403):
            raise RuntimeError(
                "бот не дал выпустить промокод: служебному админу нужно право "
                f"«{_ISSUE_RIGHT}» (без него код нельзя ограничить первой покупкой)"
            )
        if resp.status_code == 404:
            raise RuntimeError(
                "у этой сборки бота нет ручки /cabinet/admin/promocodes — выпустить "
                "код с защитой «только первая покупка» нечем"
            )
        last = _detail(resp)
        # Единственная беда, которую имеет смысл пережить повтором, — совпадение
        # случайного кода с уже существующим. Всё остальное (кривые поля)
        # повторится точно так же.
        if "already exists" not in last.lower():
            break
    raise RuntimeError(f"бот отказал в выпуске промокода: {last or 'причина неизвестна'}")


async def _revoke_code(ctx: Ctx, issued: dict[str, Any]) -> bool:
    """Убирает выпущенный код, о котором так и не удалось рассказать.

    Удаляем машинным ключом: ему их RBAC не нужен, и код исчезнет даже если
    кабинетная сессия отвалилась.

    Прогон из-за неудачи не роняем — но и одним логом больше не отделываемся:
    неудалённый код это ЖИВАЯ скидка, которую в любой момент может активировать
    кто угодно, а лог владелец не читает. Такие коды складываем в свою память и
    показываем в холостом прогоне, чтобы их можно было убрать руками.
    """
    code_id = issued.get("id")
    resp = None if code_id is None else await ctx.admin("DELETE", f"/promo-codes/{int(code_id)}")
    # 404 — кода уже нет, а это ровно то, чего мы добивались: не беда и не след.
    if resp is not None and (resp.status_code < 400 or resp.status_code == 404):
        return True
    if code_id is None:
        reason = "бот не вернул id выпущенного кода"
    elif resp is None:
        reason = "бот недоступен"
    else:
        reason = _detail(resp)
    _log(f"не удалось убрать невручённый промокод {issued.get('code')}: {reason}")
    _remember_orphan(ctx.state, issued, reason)
    return False


# --- текст ---------------------------------------------------------------------------


def _when(moment: datetime | None, tz: Any) -> str:
    return moment.astimezone(tz).strftime("%d.%m.%Y %H:%M") if moment else "—"


def _text(
    language: str,
    percent: int,
    code: str,
    ends: datetime | None,
    until: datetime | None,
    tz: Any,
) -> str:
    """Готовое сообщение. Бот шлёт его с parse_mode='HTML', поэтому всё, что
    пришло не от нас, экранируем: код из их ответа попадает в разметку."""
    title, body = _MSG.get(language, _MSG["ru"])
    return f"<b>{title.format(percent=percent)}</b>\n\n" + body.format(
        percent=percent,
        code=html.escape(code),
        ends=_when(ends, tz),
        until=_when(until, tz),
    )


def _group(skip: str) -> str:
    """Причина отказа без её переменной части — чтобы одинаковые складывались.

    «предложение уже выдавали 2026-08-06» у каждого своё число, и без этого
    сводка превратилась бы в список дат вместо счётчика. То же с числом попыток.
    """
    for head in ("предложение уже выдавали", "не доставлено"):
        if skip.startswith(head):
            return head
    return skip


def _preview(record: dict[str, Any], **extra: Any) -> dict[str, Any]:
    """Строка холостого прогона про одного человека."""
    reasons = [r for r in (record["skip"], extra.pop("skip", "")) if r]
    return {
        "user_id": record["user_id"],
        "telegram_id": record["telegram_id"],
        "language": record["language"],
        "trial_ends": record["trial_ends"],
        "would_send": not reasons,
        "skip": "; ".join(reasons) or None,
        **extra,
    }


# --- сам прогон -------------------------------------------------------------------


async def run_once(
    ctx: Ctx,
    config: dict[str, Any],
    dry_run: bool = False,
    only_user_id: int | None = None,
    limit: int | None = None,
) -> dict[str, Any]:
    """Один проход. Возвращает сводку для лога и для экрана админки.

    `dry_run=True` — холостой прогон: смотрим, кого нашли, и показываем образец
    сообщения. Ни промокода, ни отправки, ни отметки. Код в образце — заведомо
    ненастоящий (`XXXXXX`): показать живой значило бы выдать скидку ради превью.

    `only_user_id` — посмотреть одного человека вместе с причиной, по которой он
    в рассылку не попадает.
    """
    now = datetime.now(timezone.utc)
    tz, tz_name = await _bot_timezone(ctx)
    summary: dict[str, Any] = {
        "dry_run": dry_run,
        "timezone": tz_name,
        "examined": 0,
        "candidates": 0,
        "sent": 0,
        "unreachable": 0,
        "already_offered": 0,
        "failed": 0,
        # Сколько отказов оказались приговором (бот заблокирован): такие люди
        # больше не в выборке, и владелец должен видеть это отдельно от «не
        # дошло, попробуем ещё».
        "undeliverable": 0,
        "truncated": False,
        # Пусто, пока прогон не остановился на общей беде (нет прав на выпуск
        # кода, бот лёг). Строка здесь — причина, по которой остальные не
        # рассмотрены вовсе.
        "stopped": "",
        "previews": [],
    }

    users = await _bot_users(ctx)
    marks = _marks(ctx.state)
    records = _examine(users, marks, config, now)
    if only_user_id is not None:
        records = [r for r in records if r["user_id"] == only_user_id]
        if not records:
            raise _fail(404, f"Пользователь id={only_user_id} у бота не найден")

    summary["examined"] = len(records)
    summary["unreachable"] = sum(1 for r in records if r["skip"] == "нет телеграма")
    summary["already_offered"] = sum(
        1 for r in records if r["skip"].startswith("предложение уже выдавали")
    )
    summary["candidates"] = sum(1 for r in records if not r["skip"])
    # Почему остальные не попали. Без этого холостой прогон при нуле кандидатов
    # отвечает «осмотрено 7, к выдаче 0» и молчит о причине: образцы показываются
    # только тем, кому бы ушло, а два счётчика выше покрывают две причины из
    # семи. Владелец должен видеть, что это «до конца пробного далеко», а не
    # «раздел сломан».
    skipped: dict[str, int] = {}
    for record in records:
        if record["skip"]:
            group = _group(record["skip"])
            skipped[group] = skipped.get(group, 0) + 1
    summary["skipped"] = dict(sorted(skipped.items(), key=lambda pair: -pair[1]))

    percent = int(config["percent"])
    hours = int(config["lifetime_hours"])
    seen = 0       # сколько строк показали в холостом прогоне
    attempts = 0   # сколько РАЗ обращались к боту ради выдачи (не сколько удалось)
    for record in records:
        forced = only_user_id is not None
        if record["skip"] and not forced:
            continue
        if limit is not None and seen >= limit:
            summary["truncated"] = True
            break
        seen += 1

        trial_end = _stamp(record["trial_ends"])
        # Срок жизни кода считаем ДО показа: холостой прогон обязан показывать ту
        # же дату, что уедет человеку, иначе он проверяет не то, что произойдёт.
        deadline = _deadline(now, hours, trial_end)

        if dry_run:
            summary["previews"].append(
                _preview(
                    record,
                    percent=percent,
                    valid_until=deadline.isoformat(),
                    # Настоящий код здесь не выпускается сознательно: превью не
                    # должно раздавать скидки.
                    text=_text(
                        record["language"],
                        percent,
                        "X" * _CODE_BODY,
                        trial_end,
                        deadline,
                        tz,
                    ),
                )
            )
            continue
        if record["skip"]:
            continue
        # Считаем ПОПЫТКИ, а не удачи. Неудачная попытка — это три обращения к
        # боту (выпуск, отправка, отзыв), и пропускать её мимо потолка значило бы
        # пройти всю базу разом, без единой паузы, ровно в тот час, когда боту
        # плохо.
        if attempts >= _MAX_PER_RUN:
            summary["truncated"] = True
            _log(
                f"за прогон сделано {_MAX_PER_RUN} попыток — остальные уйдут "
                "следующим заходом (отметки проставлены, повторов не будет)"
            )
            break
        attempts += 1

        # Порядок строгий: сначала код, потом письмо, и не дошло — код убираем.
        try:
            issued = await _issue_code(ctx, percent, hours, deadline)
        except RuntimeError as exc:
            # Отказ в выпуске — это про ВЕСЬ прогон, а не про одного человека
            # (нет права `promocodes:create`, служебный вход отвалился, бот
            # лежит). Раньше здесь стоял `continue`, и одна общая беда
            # превращалась в столько же одинаковых строк в логе, сколько нашлось
            # кандидатов. Останавливаемся и говорим причину один раз; людям при
            # этом ничего не записываем — их вины в этом нет, в следующий заход
            # они снова кандидаты.
            summary["stopped"] = str(exc)
            _log(f"прогон остановлен: {exc}")
            break

        text = _text(
            record["language"],
            percent,
            issued["code"],
            trial_end,
            _stamp(issued["valid_until"]) or deadline,
            tz,
        )
        try:
            ok, reason, code = await bot_session.send(ctx, record["user_id"], text)
        except Exception:  # noqa: BLE001 — вернём код и понесём беду дальше
            # Отправка умеет не только «не дошло», но и упасть: служебный вход
            # перестал пускать (пароль сменили) — это RuntimeError, а не ответ
            # бота. Прогон на этом кончится, и без отзыва здесь только что
            # выпущенный код остался бы висеть у них навсегда — никому не
            # вручённый и ни на что не годный. Отмену прогона (остановка
            # адаптера) сюда сознательно не ловим: сеть в этот момент уже
            # обрывают, отозвать всё равно не выйдет — а такой код сам погаснет
            # по `valid_until`.
            await _revoke_code(ctx, issued)
            raise
        if not ok:
            summary["failed"] += 1
            # Код без адресата не нужен никому, кроме сборщиков чужих промокодов.
            await _revoke_code(ctx, issued)
            # Отметку «выдано» на неудаче ставить нельзя — человек не получил
            # ничего. Но и забывать попытку нельзя: заход повторяется каждый час
            # всё окно выдачи, и без памяти о неудаче на одного заблокировавшего
            # бота уходят сотни циклов «выпустили — не дошло — удалили».
            forever = code in _NEVER_AGAIN
            _mark_failure(ctx.state, marks, record["mark_key"], now, forever)
            if forever:
                summary["undeliverable"] += 1
            _log(
                f"user_id={record['user_id']}: не доставлено — {reason}"
                + (" (больше не пробуем)" if forever else "")
            )
            # Пауза нужна и здесь: боту от неудачной попытки не легче, чем от
            # удачной, — обращений даже больше.
            await asyncio.sleep(_SEND_PAUSE)
            continue

        summary["sent"] += 1
        # Отметку пишем сразу: контейнер перезапускают при каждом обновлении, и
        # сохранение «в конце прогона» означало бы второе предложение тем, кому
        # уже написали. Перечитывать marks не нужно — этот словарь наш на прогон,
        # а параллельного прогона у задачи не бывает (scheduler не накладывает
        # запуск на запуск).
        marks[record["mark_key"]] = now.strftime("%Y-%m-%d")
        _save_marks(ctx.state, marks)
        await asyncio.sleep(_SEND_PAUSE)

    summary["attempts"] = attempts
    return summary


@task("trial-discount", hours=1, run_at_start=False, timeout=1800)
async def trial_discount(ctx: Ctx) -> None:
    """Фоновая выдача скидки триальщикам.

    Раз в час: окно выдачи — не меньше суток (`days_before` ≥ 1 дня), спешить
    некуда, а редкий заход дешевле для бота. Почти всегда задача уходит сразу —
    проверка тумблера стоит одного чтения своей SQLite, без единого запроса
    наружу. `run_at_start=False` обязателен: иначе каждое обновление контейнера
    начиналось бы с раздачи скидок.
    """
    config = _config(ctx.state)
    if not config["enabled"]:
        return

    if not _delivery_configured():
        # Включили раньше, а доступ для отправки пропал (или его и не было).
        # Молча ничего не делать нельзя: раз в час пишем, чего не хватает.
        _log(f"выдача остановлена. {bot_session.NO_DELIVERY}")
        return

    tz, tz_name = await _bot_timezone(ctx)
    if _is_quiet(datetime.now(tz)):
        # Не пропуск, а перенос: окно выдачи длиннее тихой паузы, человек
        # дождётся своего письма утром того же окна.
        return

    summary = await run_once(ctx, config)
    if summary["candidates"] or summary["failed"]:
        # Молчим, когда предлагать некому: строка «нашли 0» раз в час — это шум,
        # в котором потом не найти настоящую беду.
        _log(
            "осмотрено {examined}, к выдаче {candidates}, выдано {sent}, "
            "без телеграма {unreachable}, уже предлагали {already_offered}, "
            "не удалось {failed} (из них навсегда {undeliverable}) "
            "(пояс {tz})".format(**summary, tz=tz_name)
        )


